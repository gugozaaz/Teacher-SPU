def style_table(ws, header_row=1, max_col=None, header_bg="E2E8F0", header_fg="0F172A"):
    ws.views.sheetView[0].showGridLines = True
    header_fill = PatternFill(start_color=header_bg, end_color=header_bg, fill_type="solid")
    header_font = Font(name="Noto Sans Thai", size=10, bold=True, color=header_fg)
    data_font = Font(name="Noto Sans Thai", size=10, color="1E293B")
    
    thin_border = Border(
        left=Side(style='thin', color='CBD5E1'),
        right=Side(style='thin', color='CBD5E1'),
        top=Side(style='thin', color='CBD5E1'),
        bottom=Side(style='thin', color='CBD5E1')
    )
    
    max_c = max_col or ws.max_column
    for row in ws.iter_rows(min_row=header_row, max_row=ws.max_row, min_col=1, max_col=max_c):
        for cell in row:
            if cell.row == header_row:
                cell.fill = header_fill
                cell.font = header_font
                cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            else:
                if not cell.font or cell.font.name != "Noto Sans Thai":
                    cell.font = data_font
                if cell.alignment.horizontal is None:
                    cell.alignment = Alignment(vertical="center")
            cell.border = thin_border
            
    for col in ws.columns:
        if col[0].column > max_c:
            continue
        col_letter = get_column_letter(col[0].column)
        max_len = 0
        for cell in col:
            val_str = str(cell.value or '')
            lines = val_str.split('\n')
            for line in lines:
                if len(line) > max_len:
                    max_len = len(line)
        ws.column_dimensions[col_letter].width = min(max(max_len + 4, 14), 50)

